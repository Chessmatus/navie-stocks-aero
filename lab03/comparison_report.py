def table(report,name='well'):
    lines=['| Вариант | Маска | Ветвей | Допущено графов | Валидация | Перенос E_int | Общий тест |',
        '|---|---:|---:|---:|---:|---:|---:|']
    for key,q in report['datasets'][name]['cases'].items():
        s=q['selected']
        fmt=(lambda x:f'{x:.2%}') if name=='well' else (lambda x:f'{x:.3e}')
        lines.append(f"| {SHORT[key]} | {s['mask']} | {s['complexity']} | {q['allowed_count']} | "
            f"{fmt(s['validation_pressure'])} | {fmt(s['intervention_pressure'])} | {fmt(q['test_pressure_error'])} |")
    return '\n'.join(lines)


