def make_figures(report):
    import matplotlib
    matplotlib.use('Agg')
    import matplotlib.pyplot as plt
    keys=list(SHORT);labels=['1. Текущий','2. Без сложности','3. + исходный фильтр']
    data=report['datasets']['well']['cases'];colors=['#275d8c','#d69b40','#a52c35']
    fig,axes=plt.subplots(1,3,figsize=(11.8,3.8),layout='constrained')
    for ax,field,title in zip(axes,['validation_pressure','intervention_pressure','test_pressure_error'],
            ['Основная валидация','Перенос: две траектории','Общий тест (постфактум)']):
        values=[(data[k][field] if field=='test_pressure_error' else data[k]['selected'][field])*100 for k in keys]
        bars=ax.bar(np.arange(3),values,color=colors)
        ax.bar_label(bars,labels=[f'{v:.2f}%' for v in values],padding=3,fontsize=10)
        ax.set(xticks=np.arange(3),xticklabels=['1','2','3'],xlabel='Вариант критерия',title=title,ylim=(0,max(values)*1.25))
    axes[0].set_ylabel('Относительная L2-ошибка давления, %')
    fig.savefig(ROOT/'figures/criterion_variants_errors.png',dpi=170,bbox_inches='tight');plt.close(fig)
    fig,ax=plt.subplots(figsize=(9.6,3.5),layout='constrained')
    for row,key in enumerate(keys):
        selected=bits(data[key]['selected']['mask'])
        ax.scatter(np.arange(6),np.full(6,2-row),s=350,c=np.where(selected,colors[row],'#eeeeee'),edgecolors='#777')
    ax.set(yticks=[2,1,0],yticklabels=labels,xticks=np.arange(6),
        xticklabels=['Поток x','Поток y','Смешанный','Затухание','Линейный','Кубический'],
        xlim=(-.6,5.6),ylim=(-.5,2.5),title='The Well: включённые ветви выбранных графов')
    fig.savefig(ROOT/'figures/criterion_variants_branches.png',dpi=170,bbox_inches='tight');plt.close(fig)
